function S(reasoning, marks, markCode, part) {
  const step = { reasoning, marks, markCode };
  if (part) step.part = part;
  return step;
}

function M(principles, steps, finalAnswer, commonErrors) {
  const markscheme = { principles, steps, finalAnswer };
  if (commonErrors) markscheme.commonErrors = commonErrors;
  return markscheme;
}

function Q(id, difficulty, totalMarks, stem, response, valueA, valueB) {
  const question = { id, difficulty, totalMarks, stem };
  const parts = Array.isArray(valueA) ? valueA : valueB;
  const markscheme = Array.isArray(valueA) ? valueB : valueA;
  if (parts) question.parts = parts;
  question.response = response;
  question.markscheme = markscheme;
  return question;
}

function open() {
  return { type: "open" };
}

function mcq(correct, choices) {
  return {
    type: "mcq",
    choices: choices.map((text, index) => ({ id: String.fromCharCode(97 + index), text })),
    correctChoiceId: String.fromCharCode(96 + correct),
  };
}


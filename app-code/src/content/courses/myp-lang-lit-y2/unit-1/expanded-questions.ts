import type {
  Difficulty,
  MarkPrinciple,
  MarkStep,
  Question,
  QuestionPart,
  TextExtract,
} from "../../../types.ts";

type PrincipleInput = Pick<MarkPrinciple, "kind" | "name" | "statement">;
type StepInput = Pick<MarkStep, "reasoning" | "marks" | "markCode"> &
  Partial<Pick<MarkStep, "part" | "evidence" | "working">>;

const principle = (
  kind: MarkPrinciple["kind"],
  name: string,
  statement: string,
): PrincipleInput => ({ kind, name, statement });
const letter = (index: number): string => String.fromCharCode(97 + index);

const mcq = (
  id: string,
  difficulty: Difficulty,
  stem: string,
  choices: [string, string, string, string],
  correct: number,
  principle: PrincipleInput,
  reasoning: string,
  finalAnswer: string,
  extract?: TextExtract,
  markCode: MarkStep["markCode"] = "A",
): Question => ({
  id,
  difficulty,
  totalMarks: 1,
  ...(extract ? { extract } : {}),
  stem,
  response: {
    type: "mcq",
    choices: choices.map((text, index) => ({ id: letter(index), text })),
    correctChoiceId: letter(correct),
  },
  markscheme: {
    principles: [principle],
    steps: [{ reasoning, marks: 1, markCode }],
    finalAnswer,
  },
});

const numeric = (
  id: string,
  difficulty: Difficulty,
  stem: string,
  answer: number,
  principle: PrincipleInput,
  reasoning: string,
  finalAnswer: string,
  extract?: TextExtract,
): Question => ({
  id,
  difficulty,
  totalMarks: 1,
  ...(extract ? { extract } : {}),
  stem,
  response: { type: "numeric", parts: [{ label: "Answer", answer }] },
  markscheme: {
    principles: [principle],
    steps: [
      {
        reasoning,
        marks: 1,
        markCode:
          reasoning.startsWith("Criterion D")
            ? "D"
            : reasoning.startsWith("Criterion C")
              ? "C"
              : reasoning.startsWith("Criterion B")
                ? "B"
                : "A",
      },
    ],
    finalAnswer,
  },
});

const open = (
  id: string,
  difficulty: Difficulty,
  totalMarks: number,
  stem: string,
  principle: PrincipleInput,
  steps: StepInput[],
  finalAnswer: string,
  extract?: TextExtract,
  parts?: QuestionPart[],
): Question => ({
  id,
  difficulty,
  totalMarks,
  ...(extract ? { extract } : {}),
  stem,
  ...(parts ? { parts } : {}),
  response: { type: "open" },
  markscheme: { principles: [principle], steps, finalAnswer },
});


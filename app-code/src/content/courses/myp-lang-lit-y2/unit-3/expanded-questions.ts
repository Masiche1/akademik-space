type PrincipleInput = Pick<MarkPrinciple, "kind" | "name" | "statement">;
type StepInput = Pick<MarkStep, "reasoning" | "marks" | "markCode"> &
  Partial<Pick<MarkStep, "part" | "evidence" | "working">>;

const principle = (
  kind: MarkPrinciple["kind"],
  name: string,
  statement: string,
): PrincipleInput => ({ kind, name, statement });
const letter = (index: number): string => String.fromCharCode(97 + index);

const MCQ_SPECIAL = /all of the (above|these)|none of the (above|these)|none of these|\b[abcd]\s+and\s+[abcd]\b/i;
const mcqSeed = (s: string): number => {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
};
const mcqOrder = (texts: readonly string[], seed: string): number[] | null => {
  if (texts.some((t) => MCQ_SPECIAL.test(t))) return null;
  let a = mcqSeed(seed);
  const rnd = () => {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const order = texts.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order.every((v, i) => v === i) && order.length > 1 ? [order[1], order[0], ...order.slice(2)] : order;
};
const letterOf = (i: number): string => String.fromCharCode(97 + i);
const letterMapOf = (order: number[]): Record<string, string> =>
  Object.fromEntries(order.map((oldI, pos) => [letterOf(oldI), letterOf(pos)]));
const remapLetters = (s: string, map: Record<string, string> | null): string =>
  map ? s.replace(/\(([abcd])\)/g, (m, L) => (map[L] ? "(" + map[L] + ")" : m)) : s;

const mcq = (
  id: string,
  difficulty: Difficulty,
  stem: string,
  choices: [string, string, string, string],
  correct: number,
  principle: PrincipleInput,
  reasoning: string,
  finalAnswer: string,
  extract?: TextExtract,
  markCode: MarkStep["markCode"] = "A",
): Question => {
  const __o = mcqOrder(choices, id);
  const __choices = (__o ? __o.map((i) => choices[i]) : choices) as [string, string, string, string];
  const __correct = __o ? __o.indexOf(correct) : correct;
  const __lmap = __o ? letterMapOf(__o) : null;
  return {
    id,
    difficulty,
    totalMarks: 1,
    ...(extract ? { extract } : {}),
    stem,
    response: {
      type: "mcq",
      choices: __choices.map((text, index) => ({ id: letter(index), text })),
      correctChoiceId: letter(__correct),
    },
    markscheme: {
      principles: [principle],
      steps: [{ reasoning: remapLetters(reasoning, __lmap), marks: 1, markCode }],
      finalAnswer: remapLetters(finalAnswer, __lmap),
    },
  };
};

const numeric = (
  id: string,
  difficulty: Difficulty,
  stem: string,
  answer: number,
  principle: PrincipleInput,
  reasoning: string,
  finalAnswer: string,
  extract?: TextExtract,
): Question => ({
  id,
  difficulty,
  totalMarks: 1,
  ...(extract ? { extract } : {}),
  stem,
  response: { type: "numeric", parts: [{ label: "Answer", answer }] },
  markscheme: {
    principles: [principle],
    steps: [
      {
        reasoning,
        marks: 1,
        markCode:
          reasoning.startsWith("Criterion D")
            ? "D"
            : reasoning.startsWith("Criterion C")
              ? "C"
              : reasoning.startsWith("Criterion B")
                ? "B"
                : "A",
      },
    ],
    finalAnswer,
  },
});

const open = (
  id: string,
  difficulty: Difficulty,
  totalMarks: number,
  stem: string,
  principle: PrincipleInput,
  steps: StepInput[],
  finalAnswer: string,
  extract?: TextExtract,
  parts?: QuestionPart[],
): Question => ({
  id,
  difficulty,
  totalMarks,
  ...(extract ? { extract } : {}),
  stem,
  ...(parts ? { parts } : {}),
  response: { type: "open" },
  markscheme: { principles: [principle], steps, finalAnswer },
});

